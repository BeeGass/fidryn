    #[test]
    fn draft_marks_follow_the_recorded_status() {
        let files = [
            ok("examples/a/pass.fr"),
            fails("examples/states/b/fail.fr", &[("E210", 1)]),
        ];
        let md = "| `examples/a/pass.fr` (draft) | `examples/states/b/fail.fr` |\nSee `b/fail.fr`, examples/states/b/fail.fr and `elsewhere/unknown.fr`.\n\n```sh\nfidryn check examples/states/b/fail.fr\n```\n";
        let marked = "| `examples/a/pass.fr` | `examples/states/b/fail.fr` (draft) |\nSee `b/fail.fr` (draft), examples/states/b/fail.fr (draft) and `elsewhere/unknown.fr`.\n\n```sh\nfidryn check examples/states/b/fail.fr\n```\n";
        assert_eq!(
            apply_draft_marks(&files, "examples/states/README.md", md),
            marked
        );
        assert_eq!(
            apply_draft_marks(&files, "examples/states/README.md", marked),
            marked
        );
    }

    #[test]
    fn check_fails_when_a_recorded_result_changes() {
        let root = scratch("changed");
        seed_documents(&root);
        write(
            &root,
            "examples/a/ok.fr",
            &module("Scratch.Ok", "query q() -> Int { return 7 }"),
        );
        update(&root).unwrap();
        check(&root).unwrap();

        write(
            &root,
            "examples/a/ok.fr",
            &module("Scratch.Ok", "query q() -> Int { return true }"),
        );
        let error = check(&root).unwrap_err().to_string();
        assert!(error.contains("examples/a/ok.fr"), "{error}");

        update(&root).unwrap();
        check(&root).unwrap();
    }

    #[test]
    fn update_writes_nothing_when_a_document_has_broken_markers() {
        let root = scratch("partial");
        seed_documents(&root);
        write(
            &root,
            "examples/a/ok.fr",
            &module("Scratch.Ok", "query q() -> Int { return 7 }"),
        );
        update(&root).unwrap();
        let recorded = fs::read_to_string(root.join(STATUS_JSON)).unwrap();

        write(
            &root,
            "examples/b/new.fr",
            &module("Scratch.New", "query q() -> Int { return 7 }"),
        );
        write(&root, "README.md", "text\n\nthe markers are gone\n");
        let error = update(&root).unwrap_err().to_string();
        assert!(error.contains("README.md"), "{error}");
        assert_eq!(
            fs::read_to_string(root.join(STATUS_JSON)).unwrap(),
            recorded
        );
    }

    #[test]
    fn a_missing_region_document_is_an_error_naming_the_file() {
        let root = scratch("missing-document");
        seed_documents(&root);
        write(
            &root,
            "examples/a/ok.fr",
            &module("Scratch.Ok", "query q() -> Int { return 7 }"),
        );
        fs::remove_file(root.join("docs/examples.md")).unwrap();
        for error in [check(&root).unwrap_err(), update(&root).unwrap_err()] {
            let error = error.to_string();
            assert!(error.contains("docs/examples.md"), "{error}");
        }
    }

