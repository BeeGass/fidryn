//! Records which `.fr` files pass `fidryn check` and fails when the record is stale.

use anyhow::{Context, Result, bail};
use fidryn_core::Severity;
use serde_json::{Map, Value, json};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

pub const ROOTS: [&str; 4] = ["examples", "packages", "prelude", "tests/programs"];
pub const STATUS_JSON: &str = "examples/status.json";
pub const STATUS_MD: &str = "examples/STATUS.md";

const SCHEMA: &str = "fidryn.examples-status/v0.1";

#[derive(Debug, clap::Args)]
pub struct ExamplesArgs {
    /// Rewrite the recorded status instead of checking it
    #[arg(long)]
    pub update: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FileStatus {
    /// Relative to the workspace root, `/` separators on every host.
    pub path: String,
    pub ok: bool,
    /// Error code to count. Empty when `ok`.
    pub codes: BTreeMap<String, u32>,
}

fn collect(dir: &Path, rel: &str, out: &mut Vec<String>) -> Result<()> {
    let entries = fs::read_dir(dir).with_context(|| format!("read directory {rel}"))?;
    for entry in entries {
        let entry = entry.with_context(|| format!("read directory {rel}"))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let child = format!("{rel}/{name}");
        let path = entry.path();
        if path.is_dir() {
            collect(&path, &child, out)?;
        } else if path.extension().is_some_and(|ext| ext == "fr") {
            out.push(child);
        }
    }
    Ok(())
}

pub fn fr_files(root: &Path) -> Result<Vec<String>> {
    let mut files = Vec::new();
    for top in ROOTS {
        let dir = root.join(top);
        if dir.is_dir() {
            collect(&dir, top, &mut files)?;
        }
    }
    files.sort();
    Ok(files)
}

pub fn survey(root: &Path) -> Result<Vec<FileStatus>> {
    let mut statuses = Vec::new();
    for path in fr_files(root)? {
        let full = root.join(&path);
        let bytes = fs::read(&full).with_context(|| format!("read {path}"))?;
        if std::str::from_utf8(&bytes).is_err() {
            bail!("{path} is not valid UTF-8");
        }
        let status = match fidryn_cli::compile_module(&full) {
            Ok(_) => FileStatus {
                path,
                ok: true,
                codes: BTreeMap::new(),
            },
            Err(diagnostics) => {
                let mut codes = BTreeMap::new();
                for diagnostic in &diagnostics {
                    if diagnostic.code.severity() == Severity::Error {
                        *codes
                            .entry(diagnostic.code.as_str().to_owned())
                            .or_insert(0) += 1;
                    }
                }
                FileStatus {
                    path,
                    ok: false,
                    codes,
                }
            }
        };
        statuses.push(status);
    }
    Ok(statuses)
}

pub fn status_json(files: &[FileStatus]) -> String {
    let entries: Vec<Value> = files
        .iter()
        .map(|file| {
            let mut entry = Map::new();
            entry.insert("path".into(), json!(file.path));
            entry.insert("check".into(), json!(if file.ok { "ok" } else { "fails" }));
            if !file.ok {
                entry.insert("codes".into(), json!(file.codes));
            }
            Value::Object(entry)
        })
        .collect();
    let mut doc = Map::new();
    doc.insert("schema".into(), json!(SCHEMA));
    doc.insert("files".into(), Value::Array(entries));
    let mut text = serde_json::to_string_pretty(&Value::Object(doc)).expect("serialize status");
    text.push('\n');
    text
}

pub fn status_markdown(files: &[FileStatus]) -> String {
    let passing = files.iter().filter(|file| file.ok).count();
    let mut md = String::from("# Example status\n\n");
    md.push_str("Generated by `cargo xtask examples --update`. Do not edit by hand.\n\n");
    md.push_str(&format!(
        "Passing `fidryn check`: {passing} of {}.\n\n",
        files.len()
    ));
    md.push_str("| File | Result | Diagnostics |\n| --- | --- | --- |\n");
    for file in files {
        let result = if file.ok { "ok" } else { "fails" };
        let codes = file
            .codes
            .iter()
            .map(|(code, n)| format!("{code} ({n})"))
            .collect::<Vec<_>>()
            .join(", ");
        let cell = if codes.is_empty() {
            String::new()
        } else {
            format!(" {codes}")
        };
        md.push_str(&format!("| `{}` | {result} |{cell} |\n", file.path));
    }
    md
}

/// Entries of a status document keyed by path, for naming what changed.
fn entries_by_path(text: &str) -> BTreeMap<String, Value> {
    let mut map = BTreeMap::new();
    if let Ok(Value::Object(doc)) = serde_json::from_str::<Value>(text)
        && let Some(Value::Array(files)) = doc.get("files")
    {
        for file in files {
            if let Some(path) = file.get("path").and_then(Value::as_str) {
                map.insert(path.to_owned(), file.clone());
            }
        }
    }
    map
}

pub fn check(root: &Path) -> Result<()> {
    let files = survey(root)?;
    let fresh = [
        (STATUS_JSON, status_json(&files)),
        (STATUS_MD, status_markdown(&files)),
    ];
    let mut problems = Vec::new();
    let mut stale = BTreeSet::new();
    for (rel, text) in &fresh {
        match fs::read_to_string(root.join(rel)) {
            Err(_) => problems.push(format!("{rel} is missing")),
            Ok(committed) if committed != *text => {
                stale.insert(*rel);
            }
            Ok(_) => {}
        }
    }
    if stale.contains(STATUS_JSON) {
        let old = entries_by_path(&fs::read_to_string(root.join(STATUS_JSON)).unwrap_or_default());
        let new = entries_by_path(&fresh[0].1);
        for path in new.keys().filter(|path| !old.contains_key(*path)) {
            problems.push(format!("{path} is not recorded"));
        }
        for path in old.keys().filter(|path| !new.contains_key(*path)) {
            problems.push(format!("{path} is recorded but no longer exists"));
        }
        for (path, entry) in &new {
            if old.get(path).is_some_and(|recorded| recorded != entry) {
                problems.push(format!("{path} has a different check result"));
            }
        }
    }
    for rel in &stale {
        problems.push(format!("{rel} is out of date"));
    }
    if problems.is_empty() {
        return Ok(());
    }
    bail!(
        "example status is out of date:\n  {}\nrun `cargo xtask examples --update`",
        problems.join("\n  ")
    )
}

pub fn update(root: &Path) -> Result<()> {
    let files = survey(root)?;
    for (rel, text) in [
        (STATUS_JSON, status_json(&files)),
        (STATUS_MD, status_markdown(&files)),
    ] {
        let path = root.join(rel);
        fs::write(&path, text).with_context(|| format!("write {rel}"))?;
    }
    Ok(())
}

pub fn run(args: ExamplesArgs) -> Result<()> {
    let root = crate::workspace::workspace_root();
    if args.update {
        update(&root)
    } else {
        check(&root)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::PathBuf;

    use crate::test_support::{module, write};

    fn scratch(name: &str) -> PathBuf {
        crate::test_support::scratch("fidryn-xtask-examples-", name)
    }

    fn ok(path: &str) -> FileStatus {
        FileStatus {
            path: path.into(),
            ok: true,
            codes: BTreeMap::new(),
        }
    }

    fn fails(path: &str, codes: &[(&str, u32)]) -> FileStatus {
        FileStatus {
            path: path.into(),
            ok: false,
            codes: codes
                .iter()
                .map(|(code, n)| ((*code).to_owned(), *n))
                .collect(),
        }
    }

    #[test]
    fn survey_lists_fr_files_sorted_with_forward_slashes_and_records_error_codes() {
        let root = scratch("survey");
        write(
            &root,
            "examples/b/nested/bad.fr",
            &module("Scratch.Bad", "query q() -> Int { return true }"),
        );
        write(
            &root,
            "examples/a/ok.fr",
            &module("Scratch.Ok", "query q() -> Int { return 7 }"),
        );
        write(&root, "tests/programs/notes.txt", "not a module");
        assert_eq!(
            survey(&root).unwrap(),
            [
                ok("examples/a/ok.fr"),
                fails("examples/b/nested/bad.fr", &[("E210", 1)])
            ]
        );
    }

    #[test]
    fn status_json_is_stable_and_omits_codes_for_passing_files() {
        let files = [
            ok("examples/a/ok.fr"),
            fails("examples/b/bad.fr", &[("E210", 2), ("E100", 1)]),
        ];
        assert_eq!(
            status_json(&files),
            "{\n  \"schema\": \"fidryn.examples-status/v0.1\",\n  \"files\": [\n    {\n      \"path\": \"examples/a/ok.fr\",\n      \"check\": \"ok\"\n    },\n    {\n      \"path\": \"examples/b/bad.fr\",\n      \"check\": \"fails\",\n      \"codes\": {\n        \"E100\": 1,\n        \"E210\": 2\n      }\n    }\n  ]\n}\n"
        );
    }

    #[test]
    fn status_markdown_has_a_count_line_and_one_row_per_file() {
        let md = status_markdown(&[
            ok("examples/a/ok.fr"),
            fails("examples/b/bad.fr", &[("E210", 2), ("E100", 1)]),
        ]);
        assert!(md.starts_with("# Example status\n"), "{md}");
        assert!(md.contains("Passing `fidryn check`: 1 of 2.\n"), "{md}");
        assert!(md.contains("| `examples/a/ok.fr` | ok | |\n"), "{md}");
        assert!(
            md.contains("| `examples/b/bad.fr` | fails | E100 (1), E210 (2) |\n"),
            "{md}"
        );
    }

    #[test]
    fn check_fails_until_update_and_names_files_added_or_removed() {
        let root = scratch("check");
        write(
            &root,
            "examples/a/ok.fr",
            &module("Scratch.Ok", "query q() -> Int { return 7 }"),
        );
        let missing = check(&root).unwrap_err().to_string();
        assert!(missing.contains("examples/status.json"), "{missing}");
        update(&root).unwrap();
        check(&root).unwrap();

        write(
            &root,
            "examples/c/new.fr",
            &module("Scratch.New", "query q() -> Int { return 7 }"),
        );
        let added = check(&root).unwrap_err().to_string();
        assert!(added.contains("examples/c/new.fr"), "{added}");
        assert!(added.contains("cargo xtask examples --update"), "{added}");

        update(&root).unwrap();
        fs::remove_file(root.join("examples/a/ok.fr")).unwrap();
        let removed = check(&root).unwrap_err().to_string();
        assert!(removed.contains("examples/a/ok.fr"), "{removed}");
    }

    #[test]
    fn a_file_that_is_not_utf8_is_an_error_naming_the_file() {
        let root = scratch("bytes");
        fs::create_dir_all(root.join("examples")).unwrap();
        fs::write(
            root.join("examples/bytes.fr"),
            b"module X version \"0\" {\n \xff\xfe }\n",
        )
        .unwrap();
        let error = survey(&root).unwrap_err().to_string();
        assert!(error.contains("examples/bytes.fr"), "{error}");
    }
}
